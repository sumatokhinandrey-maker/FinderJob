def canon(city: str | None) -> str:
    """Название города в единственном написании: нижний регистр, без лишних
    пробелов, синонимы сведены к канону."""
    if not city:
        return ""
    value = " ".join(str(city).split()).strip(" .,;").lower().replace("ё", "е")
    value = value.replace("—", "-").replace("–", "-")
    return ALIASES.get(value, value)


def where(city: str | None) -> str | None:
    """«ru», «cis», «abroad» или None, если город незнакомый."""
    value = canon(city)
    if not value:
        return None
    if value in RUSSIA:
        return "ru"
    if value in CIS:
        return "cis"
    if value in ABROAD:
        return "abroad"
    return None


def same(one: str | None, other: str | None) -> bool:
    """Один и тот же ли это город. «Питер» и «Санкт-Петербург» — да."""
    left, right = canon(one), canon(other)
    if not left or not right:
        return False
    return left == right or left in right or right in left
